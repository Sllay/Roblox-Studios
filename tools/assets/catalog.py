#!/usr/bin/env python3
"""Shortlist a visually reviewed Creator Store candidate in one game's catalog.

This does NOT approve safety/licensing and does NOT import or publish any model.
Input candidates.json is an Actions artifact generated by discover.py.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAPS = ROOT / "games" / "maps"
SLUG = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")
ID = re.compile(r"^[1-9][0-9]*$")


class CatalogError(Exception):
    pass


def shortlist(root: Path, game: str, candidates: Path, asset_id: str, biome: str, note: str) -> Path:
    if not SLUG.fullmatch(game) or not ID.fullmatch(asset_id):
        raise CatalogError("Invalid game slug or asset ID")
    if not biome.strip() or len(biome) > 80 or not note.strip() or len(note) > 300:
        raise CatalogError("Biome and review note are required (max 80/300 characters)")
    game_dir = root / "games" / "maps" / game
    catalog_path = game_dir / "game" / "assets" / "catalog.json"
    if not (game_dir / "game.manifest.json").is_file() or not catalog_path.is_file():
        raise CatalogError(f"Unknown game or missing catalog: {game}")
    try:
        provided = json.loads(candidates.read_text(encoding="utf-8"))
        registry = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise CatalogError(f"Invalid candidate/catalog JSON: {exc}") from exc
    if provided.get("schemaVersion") != 1 or provided.get("game") != game:
        raise CatalogError("Candidate file does not belong to selected game")
    if registry.get("schemaVersion") != 1 or not isinstance(registry.get("assets"), list):
        raise CatalogError("Unsupported catalog schema")
    candidate = next((x for x in provided.get("candidates", [])
                      if isinstance(x, dict) and x.get("id") == asset_id
                      and x.get("status") == "candidate_unreviewed"), None)
    if candidate is None:
        raise CatalogError("Asset ID not found among unreviewed Creator Store candidates")
    if any(a.get("id") == asset_id for a in registry["assets"]):
        raise CatalogError("Asset ID already exists in game catalog; refusing duplicate")
    name = str(candidate.get("name") or "")[:160]
    creator = str(candidate.get("creator") or "")[:100]
    registry["assets"].append({
        "id": asset_id, "name": name, "creator": creator,
        "source": "Roblox Creator Store",
        "sourceUrl": f"https://create.roblox.com/store/asset/{asset_id}",
        "biome": biome.strip(), "reviewNote": note.strip(),
        "reviewStatus": "visual_shortlisted",
        "securityStatus": "not_inspected",
        "importStatus": "not_imported",
    })
    fd, tmp_name = tempfile.mkstemp(prefix=".catalog-", suffix=".tmp", dir=catalog_path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fp:
            json.dump(registry, fp, ensure_ascii=False, indent=2)
            fp.write("\n")
        os.replace(tmp_name, catalog_path)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)
    return catalog_path


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--game", required=True)
    p.add_argument("--candidate-json", type=Path, required=True)
    p.add_argument("--id", required=True)
    p.add_argument("--biome", required=True)
    p.add_argument("--review-note", required=True)
    args = p.parse_args(argv)
    try:
        print(f"SHORTLISTED (NOT IMPORTED): {shortlist(ROOT, args.game, args.candidate_json, args.id, args.biome, args.review_note)}")
        return 0
    except CatalogError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
